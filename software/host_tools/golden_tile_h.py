"""Write software/board/sr_app/golden_tile.h from the golden tile real0 (data/golden/real0_{in,out}.hex, made by export_rtl.py).

    .venv/bin/python software/host_tools/golden_tile_h.py
The header holds the 70x70x3 input tile (14,700 B) and the expected 128x128x3 output (49,152 B) as 64-byte aligned const arrays.
It is generated (and git-ignored): regenerate it on a fresh clone before building the board program.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GOLD = ROOT / "data" / "golden"
OUT = ROOT / "software" / "board" / "sr_app" / "golden_tile.h"


def read_hex(path, n):
    vals = [int(l, 16) for l in Path(path).read_text().split()]
    if len(vals) != n:
        sys.exit(f"{path}: {len(vals)} bytes, expected {n}")
    return vals


def array(name, vals):
    lines = [",".join(f"0x{v:02x}" for v in vals[i:i + 16]) for i in range(0, len(vals), 16)]
    return f"static const unsigned char {name}[{len(vals)}] __attribute__((aligned(64))) = {{\n" + ",\n".join(lines) + "\n};\n"


if __name__ == "__main__":
    tin, tout = read_hex(GOLD / "real0_in.hex", 14700), read_hex(GOLD / "real0_out.hex", 49152)
    OUT.write_text("/* GENERATED by software/host_tools/golden_tile_h.py from data/golden/real0 - do not edit, do not commit */\n"
                   "#ifndef SR_GOLDEN_TILE_H\n#define SR_GOLDEN_TILE_H\n\n" + array("sr_golden_in", tin) + "\n" + array("sr_golden_out", tout) + "\n#endif\n")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
