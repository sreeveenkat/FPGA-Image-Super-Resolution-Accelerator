"""Test images for the board (written to data/board/, git-ignored except its README).

    .venv/bin/python software/host_tools/make_test_images.py
1) 960x540 LR + 1920x1080 HR from ONE DIV2K *training* image (img0193): centre crop 1920x1080, LR = Pillow bicubic x2 exactly like M1's make_pair.
   THIS IS A TRAINING IMAGE: use it only for bit-exactness and speed, NEVER for quality numbers.
2) a 128x128 LR crop (centre) of the Set14 LR image 'baboon' (2x2 tiles): the first full-image test.
Also writes the LR images as SRIM raw (see software/host_tools/srim.py).
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "software" / "ai"))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from dataset.pairs import load_rgb, make_pair, save_rgb  # noqa: E402
from srim import write_srim  # noqa: E402

OUT = ROOT / "data" / "board"
README = """# data/board - test images for the ZedBoard (generated by software/host_tools/make_test_images.py, git-ignored)

| File | What |
|---|---|
| div2k_img0193_hr_1920x1080.png | centre crop (x0=60, y0=138) of DIV2K training image img0193 (2040x1356) |
| div2k_img0193_lr_960x540.png / .raw | Pillow-bicubic x2 downscale of that crop (M1 `make_pair`): the 960x540 board input |
| set14_baboon_lr_128x128.png / .raw | centre crop (x0=61, y0=56) of the Set14 LR image `baboon` (250x240): 2x2 tiles |

**The DIV2K image is a TRAINING image of the network (images img0193-img0372 were used for training).** Use it only for bit-exactness and speed checks.
It must never appear in a quality (PSNR/SSIM) table: the quality numbers come from Set5/Set14/BSD100 (`results/quality/`).

`.raw` format (SRIM): 16-byte header (magic "SRIM", u32 width, u32 height, u32 reserved, little endian) + RGB interleaved, row-major, uint8. See `software/host_tools/srim.py`.
Expected board output: `software/host_tools/expected_output.py <lr.raw> <prefix>`; compare: `compare_raw.py board.raw <prefix>.raw`.
"""


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    hr_full = load_rgb(ROOT / "data" / "train" / "HR" / "img0193.png")
    h, w = hr_full.shape[:2]
    assert w >= 1920 and h >= 1080, (w, h)
    x0, y0 = (w - 1920) // 2, (h - 1080) // 2
    lr, hr = make_pair(hr_full[y0:y0 + 1080, x0:x0 + 1920])
    assert lr.shape == (540, 960, 3) and hr.shape == (1080, 1920, 3)
    save_rgb(OUT / "div2k_img0193_hr_1920x1080.png", hr)
    save_rgb(OUT / "div2k_img0193_lr_960x540.png", lr)
    write_srim(OUT / "div2k_img0193_lr_960x540.raw", lr)
    bab = load_rgb(ROOT / "data" / "test" / "LR" / "Set14" / "baboon.png")
    bh, bw = bab.shape[:2]
    bx, by = (bw - 128) // 2, (bh - 128) // 2
    crop = bab[by:by + 128, bx:bx + 128]
    save_rgb(OUT / "set14_baboon_lr_128x128.png", crop)
    write_srim(OUT / "set14_baboon_lr_128x128.raw", crop)
    (OUT / "README.md").write_text(README)
    print(f"crop origin DIV2K ({x0},{y0}), baboon ({bx},{by}); wrote {sorted(p.name for p in OUT.iterdir())}")


if __name__ == "__main__":
    main()
