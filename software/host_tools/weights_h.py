"""Write software/board/sr_app/sr_weights.h from software/ai/quantization/qparams.npz (the frozen INT8 parameters).

    .venv/bin/python software/host_tools/weights_h.py
Used by the ARM-only baseline (sr_app/sr_swmodel.c, board test T7). Weight layout as in qparams / the .mem exports: [co][ci][ky][kx]
(depthwise: [c][0][ky][kx]). The header is generated (and git-ignored): regenerate it on a fresh clone before building T7.
"""
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
QPARAMS = ROOT / "software" / "ai" / "quantization" / "qparams.npz"
OUT = ROOT / "software" / "board" / "sr_app" / "sr_weights.h"


def array(ctype, name, vals):
    vals = [int(v) for v in np.asarray(vals).reshape(-1)]
    lines = [", ".join(str(v) for v in vals[i:i + 16]) for i in range(0, len(vals), 16)]
    return f"static const {ctype} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(lines) + "\n};\n"


if __name__ == "__main__":
    z = np.load(QPARAMS)
    parts = ["/* GENERATED by software/host_tools/weights_h.py from software/ai/quantization/qparams.npz - do not edit, do not commit */",
             "#ifndef SR_WEIGHTS_H\n#define SR_WEIGHTS_H\n#include <stdint.h>\n"]
    for n in ("L1", "L2", "L3", "L4"):
        parts.append(array("int8_t", f"sr_{n}_w", z[f"{n}_w"]))
        parts.append(array("int32_t", f"sr_{n}_b", z[f"{n}_b"]))
        parts.append(array("uint32_t", f"sr_{n}_m", z[f"{n}_m"]))
        parts.append(f"#define SR_{n}_SHIFT {int(z[f'{n}_shift'])}\n")
    parts.append(f"#define SR_ANCHOR {int(bool(z['meta_anchor'])) if 'meta_anchor' in z.files else 0}  /* 1: layer 4 is a signed residual + centre input pixel */\n")
    parts.append("#endif\n")
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
